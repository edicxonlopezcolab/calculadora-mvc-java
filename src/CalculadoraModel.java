public class CalculadoraModel 
{
    public double calcularSuma(double numero1, double numero2)
    {
        double suma = numero1 + numero2;
        return suma;
    }

    public double calcularResta(double numero1, double numero2)
    {
        double resta = numero1 - numero2;
        return resta;
    }

        public double calcularMultiplicacion(double numero1, double numero2)
    {
        double multiplicacion = numero1 * numero2;
        return multiplicacion;
    }

        public double calcularDivision(double numero1, double numero2)
    {
        double division = numero1 / numero2;
        return division;
    }
}
